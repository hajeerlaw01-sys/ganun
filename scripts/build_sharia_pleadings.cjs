const fs = require('fs');
const path = require('path');

const rawContent = fs.readFileSync(path.join(__dirname, '../public/assets/aistudio/Paste_October_23__2026_-_4_57AM_073af690'), 'utf8');

const startIdx = rawContent.indexOf('الباب الأول');
const lawText = rawContent.substring(startIdx);
const lines = lawText.split('\n');

let currentChapter = '';
const parsedArticles = [];
const articleRegex = /^المادة\s+(.+):$/;
const chapterRegex = /^(الباب\s+.+)$/;

let currentArticleNum = null;
let currentArticleChapter = '';
let currentTextLines = [];

for (let i = 0; i < lines.length; i++) {
  const line = lines[i].trim();
  if (chapterRegex.test(line)) {
    currentChapter = line.replace(/[\(\)]/g, '').trim();
  } else if (articleRegex.test(line)) {
    if (currentArticleNum) {
      parsedArticles.push({
        numText: currentArticleNum,
        chapter: currentArticleChapter,
        text: currentTextLines.join(' ').replace(/\s+/g, ' ').trim()
      });
    }
    currentArticleNum = line.match(articleRegex)[1].trim();
    currentArticleChapter = currentChapter;
    currentTextLines = [];
  } else {
    if (currentArticleNum && line && line !== 'تعديلات المادة') {
      currentTextLines.push(line);
    }
  }
}
if (currentArticleNum) {
  parsedArticles.push({
    numText: currentArticleNum,
    chapter: currentArticleChapter,
    text: currentTextLines.join(' ').replace(/\s+/g, ' ').trim()
  });
}

